String languageOf(Locale locale) => locale.languageCode == 'de' ? 'de' : 'tr';

String tr(BuildContext context, String key) {
  final lang = languageOf(Localizations.localeOf(context));
  return _strings[lang]![key] ?? _strings['tr']![key] ?? key;
}

/// BuildContext olmadan (ör. bildirim metni) kullanmak için.
String trFor(String lang, String key) => _strings[lang]?[key] ?? _strings['tr']![key] ?? key;

extension TrContext on BuildContext {
  String t(String key) => tr(this, key);
}
